"""Custom fields this app adds to standard DocTypes.

Created in code rather than exported as fixtures so that installation is
deterministic and idempotent: ``create_custom_fields`` updates an existing field
in place and inserts a missing one, so re-running is safe.

Every fieldname is prefixed ``fm_`` to avoid collisions with other apps, and
every field is stamped with one of our modules so the scoped ``fixtures`` hook in
hooks.py only ever exports our own records.
"""

